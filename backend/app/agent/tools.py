def build_podcast_rag_tool(rag_service: Optional[RAGService] = None) -> Tool:
    """Builds a native Pi Coding Agent Tool for podcast transcript Q&A."""
    service = rag_service or RAGService()

    def handler(args: Dict[str, Any], sandbox: Sandbox) -> str:
        question = args.get("question", "")
        # Ensure at least 5 chunks are retrieved so small models do not starve context
        top_k = max(5, int(args.get("top_k", 6)))

        t0 = time.time()
        logger.info(
            "PodcastRAGTool invoked | Rewritten Query: '%s' | top_k: %d",
            question, top_k,
            extra={"rewritten_query": question, "top_k": top_k}
        )
        try:
            rag_response = _run_async(service.answer(question=question, top_k=top_k))
            duration = round(time.time() - t0, 3)
            logger.info(
                "PodcastRAGTool execution finished",
                extra={"duration_s": duration, "sources_count": len(rag_response.sources)}
            )
            # Return JSON string so caller can extract both answer and sources
            return json.dumps({
                "answer": rag_response.answer,
                "sources": rag_response.sources
            })
        except Exception as exc:
            duration = round(time.time() - t0, 3)
            logger.error(
                "PodcastRAGTool execution failed: %s",
                exc,
                extra={"duration_s": duration, "question": question},
                exc_info=True
            )
            return json.dumps({
                "error": str(exc),
                "answer": f"Error searching transcripts: {exc}",
                "sources": []
            })

    return Tool(
        name="PodcastRAGTool",
        description=(
            "Search and retrieve grounded insights from Lenny's Podcast transcripts. "
            "Use this tool whenever the user asks questions, seeks advice, or inquires about "
            "product management, feature prioritization, customer retention, growth loops, "
            "metrics (e.g. CAC, LTV, NRR), hiring, or startup leadership."
        ),
        input_schema={
            "type": "object",
            "properties": {
                "question": {
                    "type": "string",
                    "description": "The specific question to search podcast transcripts for."
                },
                "top_k": {
                    "type": "integer",
                    "description": "Number of transcript chunks to retrieve (default: 5).",
                    "default": 5
                }
            },
            "required": ["question"]
        },
        handler=handler,
        mutating=False
    )


def build_ship30_tool(
    writer: Optional[Ship30Writer] = None,
    retriever: Optional[Any] = None,
) -> Tool:
    """Builds a native Pi Coding Agent Tool for Ship 30 for 30 essays."""
    essay_writer = writer or Ship30Writer(retriever=retriever)
    tool_retriever = retriever

    def _get_tool_retriever() -> Optional[Any]:
        nonlocal tool_retriever
        if tool_retriever is not None:
            return tool_retriever
        from unittest.mock import Mock, AsyncMock, MagicMock
        if isinstance(essay_writer, (Mock, AsyncMock, MagicMock)):
            return None
        if hasattr(essay_writer, "_get_retriever"):
            return essay_writer._get_retriever()
        try:
            from app.rag.retriever import Retriever
            tool_retriever = Retriever()
            return tool_retriever
        except Exception as exc:
            logger.warning("Retriever unavailable in build_ship30_tool: %s", exc)
            return None

    def handler(args: Dict[str, Any], sandbox: Sandbox) -> str:
        topic = (
            args.get("topic")
            or args.get("user_query")
            or args.get("query")
            or args.get("prompt")
            or args.get("title")
            or (next((str(v) for v in args.values() if isinstance(v, str) and v.strip()), "") if args else "")
            or ""
        )
        context = args.get("context") or args.get("context_data")

        t0 = time.time()
        logger.info(
            "Ship30Tool handler invoked by Pi Agent",
            extra={"topic": topic, "has_context": bool(context)}
        )
        try:
            # 1. Retrieve relevant transcript chunks using the existing RAG retrieval pipeline
            sources: List[str] = []
            context_data = context or ""

            if not context_data:
                active_retriever = _get_tool_retriever()
                if active_retriever:
                    try:
                        chunks = _run_async(active_retriever.retrieve(query=topic, top_k=8))
                        if chunks:
                            max_sim = max(c.similarity_score for c in chunks)
                            if max_sim < 0.65:
                                logger.info("Ship30Tool: Chunks for '%s' below similarity threshold (max %.4f < 0.65)", topic, max_sim)
                                chunks = []

                        if chunks:
                            sources = list(dict.fromkeys([c.episode_title for c in chunks]))
                            context_blocks = []
                            for i, chunk in enumerate(chunks, start=1):
                                context_blocks.append(
                                    f"--- Transcript Excerpt {i} (Episode: \"{chunk.episode_title}\") ---\n"
                                    f"{chunk.content.strip()}"
                                )
                            context_data = "\n\n".join(context_blocks)
                            logger.info(
                                "Ship30Tool retrieved %d chunks across %d episodes",
                                len(chunks), len(sources)
                            )
                    except Exception as exc:
                        logger.warning("Ship30Tool retrieval failed: %s", exc)

            # 2. Pass context_data and user_query into Ship30Writer
            essay = _run_async(essay_writer.write(
                topic=topic,
                context=context_data,
                user_query=topic,
                context_data=context_data
            ))
            all_sources = list(dict.fromkeys(sources + getattr(essay, "sources", [])))
            duration = round(time.time() - t0, 3)

            is_insufficient = (
                str(essay).strip() == "Not enough transcript evidence available."
                or "not enough transcript evidence available" in str(essay).lower()
            )

            if is_insufficient:
                logger.info("Ship30Tool: Insufficient transcript evidence found for topic '%s'", topic)
                return json.dumps({
                    "answer": "Not enough transcript evidence available.",
                    "sources": [],
                    "artifact": False,
                    "markdown_content": None,
                    "html_content": None
                })

            markdown_text = getattr(essay, "markdown_content", None) or str(essay)
            html_text = getattr(essay, "html_content", None)
            if not html_text:
                try:
                    from markdown_it import MarkdownIt
                    html_text = f'<article class="ship30-article">\n{MarkdownIt().render(markdown_text)}\n</article>'
                except Exception:
                    html_text = f'<article class="ship30-article">\n<div>{markdown_text}</div>\n</article>'

            word_count = getattr(essay, "word_count", None)
            if word_count is None and markdown_text:
                word_count = len(markdown_text.strip().split())

            logger.info(
                "Ship30Tool execution finished",
                extra={"duration_s": duration, "essay_length": len(markdown_text), "word_count": word_count, "sources_count": len(all_sources)}
            )
            return json.dumps({
                "answer": markdown_text,
                "sources": all_sources,
                "artifact": True,
                "markdown_content": markdown_text,
                "html_content": html_text,
                "word_count": word_count
            })
        except Exception as exc:
            duration = round(time.time() - t0, 3)
            logger.error(
                "Ship30Tool execution failed: %s",
                exc,
                extra={"duration_s": duration, "topic": topic},
                exc_info=True
            )
            return json.dumps({
                "error": str(exc),
                "answer": f"Error generating Ship30 essay: {exc}",
                "sources": [],
                "artifact": False,
                "markdown_content": None,
                "html_content": None
            })

    return Tool(
        name="Ship30Tool",
        description=(
            "Write and generate a complete Ship 30 for 30 style long-form article "
            "(minimum 1,000 words, target 1,250 words) grounded strictly in podcast transcripts. "
            "Follows the required structure: Hook, Problem, Insight, Lesson, Application, Action Steps, Conclusion, Sources. "
            "Use this tool whenever the user requests a Ship30 article, Ship30 essay, blog post, long-form content, newsletter, "
            "or asks to write, draft, or compose an article or essay."
        ),
        input_schema={
            "type": "object",
            "properties": {
                "topic": {
                    "type": "string",
                    "description": "The topic, theme, or title for the Ship 30 atomic essay."
                },
                "context": {
                    "type": "string",
                    "description": "Optional background context, outline, or key points to incorporate."
                }
            },
            "required": ["topic"]
        },
        handler=handler,
        mutating=False
    )



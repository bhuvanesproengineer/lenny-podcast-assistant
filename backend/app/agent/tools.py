_main_event_loop: Optional[asyncio.AbstractEventLoop] = None


def set_main_event_loop(loop: Optional[asyncio.AbstractEventLoop]) -> None:
    """Sets the primary FastAPI event loop reference for thread-safe async scheduling."""
    global _main_event_loop
    _main_event_loop = loop


def _run_async(coro: Any) -> Any:
    """Executes an async coroutine safely across both running and non-running event loops."""
    global _main_event_loop

    # If the main event loop is active and running, and we are running inside a worker thread
    if _main_event_loop is not None and _main_event_loop.is_running():
        try:
            curr_loop = asyncio.get_running_loop()
        except RuntimeError:
            curr_loop = None

        if curr_loop is not _main_event_loop:
            # Safely schedule on the main event loop preserving database connections
            future = asyncio.run_coroutine_threadsafe(coro, _main_event_loop)
            return future.result()

    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = None

    if loop and loop.is_running():
        # Execute in a dedicated worker thread to avoid blocking the running event loop
        with concurrent.futures.ThreadPoolExecutor(max_workers=1) as executor:
            return executor.submit(lambda: asyncio.run(coro)).result()
    else:
        return asyncio.run(coro)


class AgentResponse(BaseModel):
    """Structured response returned by LennyAgent."""

    selected_tool: str = Field(..., description="The name of the tool selected and executed by the agent.")
    answer: str = Field(..., description="The textual answer or content generated by the tool.")
    sources: List[str] = Field(default_factory=list, description="Source episodes or citations when available.")
    artifact: bool = Field(default=False, description="Whether this response is an artifact for Artifact Viewer.")
    markdown_content: Optional[str] = Field(default=None, description="Full markdown content of the artifact.")
    html_content: Optional[str] = Field(default=None, description="HTML rendered content of the artifact.")
    word_count: Optional[int] = Field(default=None, description="Total word count for generated articles or responses.")



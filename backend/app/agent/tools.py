class PodcastRAGTool:
    """Wrapper class providing direct .run() interface for PodcastRAGTool."""

    name: str = "PodcastRAGTool"
    description: str = "Answers questions based on podcast transcripts using RAG retrieval."

    def __init__(self, rag_service: Optional[RAGService] = None):
        self.rag_service = rag_service or RAGService()
        self.tool = build_podcast_rag_tool(self.rag_service)

    async def run(self, question: str, top_k: int = 5) -> Dict[str, Any]:
        """Direct async execution."""
        rag_response = await self.rag_service.answer(question=question, top_k=top_k)
        return {"answer": rag_response.answer, "sources": rag_response.sources}


class Ship30Tool:
    """Wrapper class providing direct .run() interface for Ship30Tool."""

    name: str = "Ship30Tool"
    description: str = "Generates an authentic Ship 30 for 30 long-form essay (~1,250 words) on a given topic."

    def __init__(self, writer: Optional[Ship30Writer] = None, retriever: Optional[Any] = None):
        self.writer = writer or Ship30Writer(retriever=retriever)
        self.retriever = retriever
        self.tool = build_ship30_tool(self.writer, retriever=self.retriever)

    async def run(self, topic: str, context: Optional[str] = None) -> str:
        """Direct async execution."""
        essay = await self.writer.write(topic=topic, context=context)
        return essay
